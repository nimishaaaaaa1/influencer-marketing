// Generate 90 days of time series data
function generateTimeSeriesData(): TimeSeriesEntry[] {
  const data: TimeSeriesEntry[] = []
  const baseDate = new Date("2025-12-18")

  for (let i = 0; i < 90; i++) {
    const date = new Date(baseDate)
    date.setDate(date.getDate() + i)

    const dayOfWeek = date.getDay()
    const weekendMultiplier = dayOfWeek === 0 || dayOfWeek === 6 ? 1.3 : 1.0
    const trendMultiplier = 1 + i * 0.005
    const noise = 0.85 + Math.sin(i * 0.3) * 0.15 + (Math.sin(i * 1.7) * 0.05)

    const reach = Math.round(120000 * weekendMultiplier * trendMultiplier * noise)
    const engagement = Math.round(reach * (0.065 + Math.sin(i * 0.2) * 0.015))
    const spend = Math.round(1200 + Math.random() * 600 + i * 5)
    const revenue = Math.round(spend * (2.8 + Math.sin(i * 0.15) * 0.8 + i * 0.01))

    data.push({
      date: date.toISOString().split("T")[0],
      reach,
      engagement,
      spend,
      revenue,
    })
  }

  return data
}

